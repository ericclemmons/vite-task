//! Executables in `node_modules/.bin`. pnpm writes them as shell, `.cmd`, and
//! `.ps1` shims that embed absolute paths of the workspace or pnpm's store;
//! npm and Yarn create symlinks to the packages' bin files instead.
//!
//! A pnpm shell shim is fingerprinted by its `# cmd-shim-target=` comment,
//! made relative to the shim's `node_modules` folder, so a shim rewritten
//! for another workspace path keeps its fingerprint, but one that now runs
//! another package version doesn't. Any other file, or a shim whose target
//! is outside that `node_modules` folder, is fingerprinted only by whether it
//! exists. What it runs is tracked through the package files the task reads.

use std::io::{self, Read as _};

use vt_path::{AbsolutePath, RelativePathBuf};

/// pnpm's shims are a few KiB. A larger file isn't one, and its content
/// isn't read past this.
const MAX_SHIM_LEN: u64 = 64 * 1024;

/// Whether `path` is directly inside a `node_modules/.bin` directory.
pub fn matches(path: &AbsolutePath) -> bool {
    path.parent().is_some_and(|dir| dir.ends_with("node_modules/.bin"))
}

/// What the shim at `path`, read from `stream`, runs: its `cmd-shim-target`
/// relative to the `node_modules` folder that holds `node_modules/.bin`.
/// `None` if `path` isn't a pnpm shell shim, or the target is outside that
/// `node_modules` folder.
pub fn shim_target(path: &AbsolutePath, stream: impl io::Read) -> io::Result<Option<RelativePathBuf>> {
    let mut content = Vec::new();
    stream.take(MAX_SHIM_LEN + 1).read_to_end(&mut content)?;
    if content.len() as u64 > MAX_SHIM_LEN {
        return Ok(None);
    }
    let Ok(content) = std::str::from_utf8(&content) else {
        return Ok(None);
    };
    let Some(target) = content.lines().rev().find_map(|line| {
        line.trim_end_matches('\r').strip_prefix("# cmd-shim-target=").map(str::trim)
    }) else {
        return Ok(None);
    };
    let Some(bin_dir) = path.parent() else {
        return Ok(None);
    };
    let Some(modules_dir) = bin_dir.parent() else {
        return Ok(None);
    };
    // Joining an absolute target replaces the shim's folder.
    let target = bin_dir.join(target).clean();
    Ok(target.strip_prefix(modules_dir).ok().flatten())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn matches_only_directly_inside_node_modules_bin() {
        let cwd = vt_path::current_dir().unwrap();
        assert!(matches(&cwd.join("node_modules/.bin/tsc")));
        assert!(matches(&cwd.join("packages/a/node_modules/.bin/tsc.cmd")));
        assert!(!matches(&cwd.join("node_modules/typescript/bin/tsc")));
        assert!(!matches(&cwd.join("node_modules/.bin")));
        assert!(!matches(&cwd.join(".bin/tsc")));
        #[cfg(windows)]
        assert!(matches(&cwd.join(r"packages\a\node_modules\.bin\tsc.ps1")));
    }
}
